#!/usr/bin/env node
/**
 * Builds the two things the emails ship as:
 *   n8n/mailer.code.js          one self-contained script for the n8n Code node "Build emails"
 *   supabase/templates/*.html   the Supabase Auth email templates (paste into Authentication → Emails,
 *                               or `supabase config push` with the [auth.email.template.*] blocks in docs/EMAILS.md)
 * Source: emails/*.mjs. Run: bun run emails:build   (and `bun run emails:check` in CI: fails if the outputs are stale).
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = (f) => readFileSync(join(root, 'emails', f), 'utf8');
const check = process.argv.includes('--check');

// Concatenate the modules in dependency order, dropping their imports and `export`s.
const strip = (code) =>
  code
    .replace(/^import .*?;\s*$/gms, '')
    .replace(/^export (const|function|async function|let|class) /gm, '$1 ')
    .replace(/\/\*[\s\S]*?\*\//g, '') // block comments (the live node is pasted through an API: keep it small)
    .replace(/^\s*\/\/.*$/gm, '') // whole-line comments
    .replace(/\n{2,}/g, '\n');
const order = ['config.mjs', 'hmac.mjs', 'render.mjs', 'templates.mjs', 'mailer.mjs'];
const header = `// n8n Code node "Build emails" in the workflow "FORGEDSA · Mailer".
// GENERATED by scripts/emails-build.mjs from emails/*.mjs: edit those, then run \`bun run emails:build\`.
// The live node holds the real signing key in MAILER_SIGNING_KEY; this copy keeps the placeholder.
// Input: the signed event posted by private.notify_mailer() (supabase/migrations/20261124090000_shared_accounts_and_mailer.sql).
`;
const tail = `
const MAILER_SIGNING_KEY = '__MAILER_SIGNING_KEY__';
const messages = handle($input.first().json, { key: MAILER_SIGNING_KEY, now: Date.now() });
if (!messages.length) throw new Error('No deliverable recipient in the event');
return messages.map((m) => ({ json: m }));
`;
const n8nCode = header + order.map((f) => `// ---- ${f}\n${strip(src(f)).trim()}`).join('\n') + tail;

const outputs = new Map([[join(root, 'n8n', 'mailer.code.js'), n8nCode]]);

const { AUTH_EMAILS } = await import(pathToFileURL(join(root, 'emails', 'auth.mjs')).href);
const { renderHtml } = await import(pathToFileURL(join(root, 'emails', 'render.mjs')).href);
for (const [name, t] of Object.entries(AUTH_EMAILS)) {
  const doc = { ...t.doc, subject: t.subject };
  outputs.set(join(root, 'supabase', 'templates', `${name}.html`), renderHtml(doc));
}

let stale = 0;
for (const [file, content] of outputs) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (check) {
    // The footer carries the current year: compare with it normalised
    const norm = (s) => (s ?? '').replace(/© \d{4}/g, '© YEAR');
    if (norm(current) !== norm(content)) { console.error(`stale: ${file}`); stale++; }
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log(`wrote ${file.replace(root + '/', '')} (${content.length} bytes)`);
  }
}
if (check && stale) { console.error('Run `bun run emails:build`.'); process.exit(1); }
